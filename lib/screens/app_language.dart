import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:jober_india/l10n/app_localizations.dart';

// One global locale notifier for the entire application.
final ValueNotifier<Locale> appLocale =
    ValueNotifier<Locale>(const Locale('en', 'IN'));

// Get the actual locale generated by Flutter.
Locale? getSupportedLocale(String languageCode) {
  for (final locale in AppLocalizations.supportedLocales) {
    if (locale.languageCode == languageCode) {
      return locale;
    }
  }

  return null;
}

Future<bool> changeAppLanguage(String languageCode) async {
  Locale? selectedLocale;

  for (final locale in AppLocalizations.supportedLocales) {
    if (locale.languageCode == languageCode) {
      selectedLocale = locale;
      break;
    }
  }

  if (selectedLocale == null) {
    debugPrint('Unsupported language: $languageCode');
    return false;
  }

  final prefs = await SharedPreferences.getInstance();
  await prefs.setString('language', languageCode);

  appLocale.value = selectedLocale;

  return true;
}

// Load saved language when the app starts.
Future<void> loadAppLanguage() async {
  final prefs = await SharedPreferences.getInstance();

  final savedCode = prefs.getString('language') ?? 'en';

  final locale = getSupportedLocale(savedCode);

  appLocale.value = locale ?? const Locale('en', 'IN');
}


